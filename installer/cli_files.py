#!/usr/bin/env python3
"""Writes the [Files] entries that put the command line in {app}\\cli, for
installer/acrux.iss to #include:

    python installer/cli_files.py <app publish> <cli publish> <out.iss>

The command line's win-x64 publish is 267 MB, and all but a few files of it
(the .NET runtime, Polars, SQLite...) are byte for byte the app's. An entry
whose source is one of the app's own files is stored once in the setup
(Inno's MergeDuplicateFiles), so those point at the app's publish and only
the rest at the command line's: the setup grows by about 1 MB, not 100.
Every entry carries "Tasks: cli", the setup's unchecked option.
"""

import hashlib
import sys
from pathlib import Path


def digest(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def main():
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    app, cli, out = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
    lines = ["; generated by installer/cli_files.py: the command line in {app}\\cli"]
    shared = own = 0
    for f in sorted(p for p in cli.rglob("*") if p.is_file() and p.suffix != ".pdb"):
        rel = f.relative_to(cli)
        twin = app / rel
        if twin.is_file() and twin.stat().st_size == f.stat().st_size and digest(twin) == digest(f):
            source, shared = "{#PublishDir}", shared + 1
        else:
            source, own = "{#CliDir}", own + 1
        sub = "" if rel.parent == Path(".") else "\\" + str(rel.parent).replace("/", "\\")
        name = str(rel).replace("/", "\\")
        lines.append(f'Source: "{source}\\{name}"; DestDir: "{{app}}\\cli{sub}"; '
                     "Tasks: cli; Flags: ignoreversion")
    if not (cli / "acrux.exe").is_file():
        raise SystemExit(f"{cli}: no acrux.exe (rename Acrux.Cli.exe first)")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"cli_files: {shared} files shared with the app, {own} of the command line's own -> {out}",
          file=sys.stderr)


if __name__ == "__main__":
    main()
